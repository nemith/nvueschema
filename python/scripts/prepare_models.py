"""Generate all packaged models from checksum-pinned NVUE schemas.

Run from python/: uv run --no-project python scripts/prepare_models.py
Use --spec-dir to consume predownloaded schemas without network access.
"""

import argparse
import hashlib
import json
import os
import subprocess
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec-dir", type=Path)
    args = parser.parse_args()
    if args.spec_dir is not None:
        args.spec_dir = args.spec_dir.resolve()
    cache = ROOT / "python/.cache"
    cache.mkdir(parents=True, exist_ok=True)
    binary = cache / ("nvueschema.exe" if os.name == "nt" else "nvueschema")
    subprocess.run(
        ["go", "build", "-o", str(binary), "./cmd/nvueschema"], cwd=ROOT, check=True
    )
    manifest = json.loads((ROOT / "testdata/schema-versions.json").read_text())
    destination = ROOT / "python/nvueschema/src/nvueschema/models"

    def generate(entry):
        version, expected = entry["version"], entry["sha256"]
        spec = (args.spec_dir or cache) / f"openapi-{version}.json"
        if spec.exists():
            data = spec.read_bytes()
        elif args.spec_dir:
            raise FileNotFoundError(spec)
        else:
            request = urllib.request.Request(
                entry["url"], headers={"User-Agent": "cumulus-schema/1.0"}
            )
            with urllib.request.urlopen(request, timeout=90) as response:
                data = response.read()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError(
                f"NVUE {version} checksum changed; review the version manifest before regenerating"
            )
        if not spec.exists():
            spec.write_bytes(data)
        source = subprocess.check_output(
            [str(binary), "gen", str(spec), "-f", "pydantic"], cwd=ROOT
        )
        header = f"# Generated by python/scripts/prepare_models.py; do not edit.\n# NVUE {version}; source SHA256: {expected}\n"
        target = destination / f"v{version.replace('.', '_')}.py"
        target.write_bytes(header.encode() + source)
        print(f"Generated {target.name}", flush=True)

    with ThreadPoolExecutor(max_workers=4) as pool:
        list(pool.map(generate, manifest))
    versions = tuple(entry["version"] for entry in manifest)
    (destination / "_versions.py").write_text(
        f"# Generated release manifest.\nVERSIONS = {versions!r}\n"
    )


if __name__ == "__main__":
    main()
